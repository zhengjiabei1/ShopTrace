#!/usr/bin/env python3
"""Build the portal from saved batch records.

Reads local files.
One --suite may be passed per mechanism arm; entries with the same suite ID merge.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import tempfile
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parent
SUITE_INFO = {
    "english": ("Acceptance · 9ade785", "Earlier browser task acceptance results."),
    "release-regression": ("Release regression", "Original browser tasks checked with the integrated release."),
    "model-regression": ("Model regression", "Five current-tree repeats of the six base browser tasks."),
    "stability": ("Stability", "Repeated runs of six tasks using a fixed version."),
    "development": ("Development", "Compare context settings under the same conditions."),
    "heldout": ("Held-out", "Check the selected setting on independent cases."),
    "procurement-pilot": ("Procurement pilot", "Check cross-page shopping and recovery before comparison."),
    "procurement-dev": ("Recovery comparison", "Compare recovery settings on the same tasks and faults."),
    "procurement-heldout": ("Procurement held-out", "Check the selected setting on held-out constraint combinations."),
    "procurement-memory": ("Page memory", "Compare context settings on cross-page tasks."),
}
TASK_NAMES = {
    "browser-headphones-commute": "Commuter headphones", "browser-thermos-variant": "Thermos options",
    "browser-powerbank-spec": "Power bank specs", "browser-lamp-adjustable": "Reading lamp",
    "browser-thermos-budget": "No suitable item", "browser-headphones-unknown": "Missing information",
}


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def safe_child(root, relative):
    path = (root / relative).resolve()
    if not path.is_relative_to(root.resolve()):
        raise ValueError("Evidence path escapes its batch directory")
    return path


def parse_suite(value):
    try:
        label, path = value.split("=", 1)
        suite, _, arm = label.partition(":")
        if not re.fullmatch(r"[a-z][a-z0-9_-]{0,40}", suite):
            raise ValueError()
        if arm and not re.fullmatch(r"[a-z][a-z0-9_-]{0,60}", arm):
            raise ValueError()
        return suite, arm, Path(path).resolve()
    except ValueError as exc:
        raise argparse.ArgumentTypeError("Expected SUITE[:ARM]=BATCH_DIRECTORY") from exc


def _build(specs, destination, *, live_url=None, archive_url=None, allow_incomplete=False, offset=0):
    destination = Path(destination).resolve()
    destination.mkdir(parents=True, exist_ok=True)
    generated = destination / "evidence"
    if generated.exists():
        if generated.is_symlink() or not (generated / ".shoptrace-generated").is_file():
            raise ValueError("Refusing to replace a non-generated evidence directory")
        shutil.rmtree(generated)
    generated.mkdir()
    (generated / ".shoptrace-generated").write_text("Generated by portal/build_report.py\n")
    report = {"schema_version": "shoptrace.portal.v1", "generated_at": datetime.now(timezone.utc).isoformat(),
              "model": None, "source_commit": None, "live_url": live_url, "archive_url": archive_url,
              "note": "Every attempt retained; unknown outcomes reported separately.", "suites": []}
    suites, models, commits, seen_ids = {}, set(), set(), set()
    secrets = [os.environ[name].encode() for name in ("LLM_API_KEY", "OPENAI_API_KEY", "GITHUB_TOKEN", "GH_TOKEN") if os.environ.get(name)]

    def copy(src, dst):
        if src.is_symlink() or not src.resolve().is_relative_to(batch_root.resolve()):
            raise ValueError("Evidence file escapes its batch directory")
        content = src.read_bytes()
        if any(value in content for value in secrets):
            raise ValueError("Configured credential found in evidence; publication stopped")
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_bytes(content)

    for group_i, (suite_id, arm, batch_root) in enumerate(specs, offset):
        source = batch_root / "batch.json"
        if not source.is_file():
            source = batch_root / "summary.json"
        if not source.is_file():
            raise ValueError("Batch directory has neither batch.json nor summary.json")
        state = read(source)
        if not allow_incomplete and state.get("status") in {"running", "planned", "collecting", "round_2_running"}:
            raise ValueError("Batch is still running; build only completed evidence or use --allow-incomplete")
        title, desc = SUITE_INFO.get(suite_id, (suite_id, "Saved model evaluation runs."))
        if suite_id not in suites:
            suites[suite_id] = {"id": suite_id, "title": title, "description": desc, "attempts": []}
            report["suites"].append(suites[suite_id])
        commit = state.get("base_commit") or state.get("source_commit") or (state.get("runner_source") or {}).get("commit")
        if commit:
            commits.add(commit)
        titles = {}
        for name in ("task-metadata.json", "case-metadata.json"):
            meta_path = batch_root / name
            if not meta_path.is_file():
                continue
            meta = read(meta_path)
            if isinstance(meta, dict):
                meta = meta.get("tasks") or meta.get("cases") or []
            if isinstance(meta, list):
                titles.update({row["id"]: row.get("title", row["id"]) for row in meta if isinstance(row, dict) and "id" in row})
        for index, receipt in enumerate(state.get("attempts", [])):
            folder = safe_child(batch_root, receipt.get("folder", ""))
            trace_path = folder / "trajectory.json"
            document = read(trace_path) if trace_path.is_file() else {"events": []}
            run = document.get("run") or receipt.get("run") or receipt
            run_id = run.get("run_id") or receipt.get("run_id") or f"unsubmitted-{group_i}-{index}"
            if run_id in seen_ids:
                raise ValueError("The same attempt is present in more than one portal input")
            seen_ids.add(run_id)
            model = (run.get("model") or {}).get("name") or state.get("model")
            if model:
                models.add(model)
            result = run.get("result") or {}
            usage = run.get("usage") or {}
            cfg = run.get("runtime") or {}
            case = run.get("benchmark_case") or {}
            stopped = run.get("termination_reason") == "process_interrupted"
            task_id = run.get("task_id") or receipt.get("task_id") or "unknown"
            out_dir = generated / f"group-{group_i:02d}" / f"attempt-{index + 1:03d}"
            out_dir.mkdir(parents=True)
            attempt = {"id": run_id, "task_id": task_id, "task_title": titles.get(task_id) or TASK_NAMES.get(task_id, task_id),
                       "repeat": receipt.get("repeat") or receipt.get("round") or receipt.get("attempt") or 1,
                       "arm": arm or cfg.get("recovery") or cfg.get("context_mode", "full_history"),
                       "source": run.get("source") or receipt.get("source") or "unknown",
                       "model": model,
                       "status": run.get("status") or receipt.get("submission_state") or "unknown",
                       "success": result.get("success"), "result_reason": result.get("reason"),
                       "elapsed_seconds": None if stopped else run.get("elapsed_seconds"), "model_calls": run.get("model_calls"),
                       "time_note": "Elapsed time unavailable after process interruption." if stopped else None,
                       "input_tokens": usage.get("input_tokens"), "output_tokens": usage.get("output_tokens"),
                       "error": run.get("error") or receipt.get("collection_error"), "steps": [],
                       "protocol": {"prompt_hash": run.get("prompt_hash"), "tools_hash": run.get("tools_hash"), "context_policy": run.get("context_policy"),
                                    "source": run.get("source_fingerprint"), "runtime": cfg,
                                    "dataset": case.get("dataset_fingerprint")},
                       "conditions": {key: case.get(key, cfg.get(key)) for key in ("fault", "seed", "split")},
                       "recovery": cfg.get("recovery"), "context_mode": cfg.get("context_mode", "full_history"),
                       "metrics": result.get("metrics") or {}}
            for src_name, key in (("trajectory.json", "trajectory_url"), ("result.json", "result_url")):
                if (folder / src_name).is_file():
                    copy(folder / src_name, out_dir / src_name)
                    attempt[key] = (out_dir / src_name).relative_to(destination).as_posix()
            events = document.get("events", [])
            actions = {event.get("payload", {}).get("step"): event.get("payload", {}).get("action") for event in events if event.get("type") == "action"}
            errors, notes = {}, {}
            for event in events:
                if event.get("type") == "error":
                    errors.setdefault(event.get("payload", {}).get("step"), []).append(event.get("payload"))
                if event.get("type") == "action" and event.get("payload", {}).get("action", {}).get("type") == "finish":
                    attempt["finish"] = event["payload"]["action"]
                if event.get("type") in {"memory", "recovery"}:
                    note = {"type": event["type"], **(event.get("payload") or {})}
                    notes.setdefault(note.get("step"), []).append(note)
            for event in events:
                if event.get("type") != "observation":
                    continue
                payload = event.get("payload") or {}; obs = payload.get("observation") or {}; step = payload.get("step")
                item = {"step": step, "url": obs.get("url"), "text": obs.get("text"), "action": actions.get(step), "error": errors.get(step),
                        "notes": notes.get(step, [])}
                shot = obs.get("screenshot")
                if isinstance(shot, str) and Path(shot).name == shot:
                    image = folder / "screenshots" / shot
                    if image.is_file():
                        copy(image, out_dir / "screenshots" / shot)
                        item["screenshot"] = (out_dir / "screenshots" / shot).relative_to(destination).as_posix()
                attempt["steps"].append(item)
            suites[suite_id]["attempts"].append(attempt)
    report["model"] = next(iter(models)) if len(models) == 1 else " / ".join(sorted(models)) or None
    report["source_commit"] = next(iter(commits)) if len(commits) == 1 else None
    report["source_commits"] = sorted(commits)
    raw = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    if any(value in raw.encode() for value in secrets):
        raise ValueError("Configured credential found in report")
    (destination / "report.json").write_text(raw, encoding="utf-8")
    encoded = json.dumps(report, ensure_ascii=False).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
    (destination / "report-data.js").write_text("window.SHOPTRACE_REPORT = " + encoded + ";\n", encoding="utf-8")
    files = [{"path": p.relative_to(destination).as_posix(), "bytes": p.stat().st_size, "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
             for p in sorted(destination.rglob("*")) if p.is_file() and p.name != "manifest.json"]
    (destination / "manifest.json").write_text(json.dumps({"schema_version": "shoptrace.portal.manifest.v1", "files": files}, indent=2) + "\n")
    return report


def _merge(old, new):
    """Keep prior attempts and their download destinations."""
    seen = {row["id"] for suite in old["suites"] for row in suite["attempts"]}
    suites = {suite["id"]: suite for suite in old["suites"]}
    for suite in new["suites"]:
        for row in suite["attempts"]:
            if row["id"] in seen:
                raise ValueError("The same attempt is already present in the saved portal")
            seen.add(row["id"])
        if new.get("archive_url"):
            suite["archive_url"] = new["archive_url"]
        if suite["id"] in suites:
            suites[suite["id"]]["attempts"].extend(suite["attempts"])
        else:
            old["suites"].append(suite)
            suites[suite["id"]] = suite
    old["generated_at"] = new["generated_at"]
    models = {part for data in (old, new) for part in (data.get("model") or "").split(" / ") if part}
    old["model"] = " / ".join(sorted(models)) or None
    commits = set(old.get("source_commits", [])) | set(new.get("source_commits", []))
    old["source_commits"] = sorted(commits)
    old["source_commit"] = next(iter(commits)) if len(commits) == 1 else None
    if new.get("live_url"):
        old["live_url"] = new["live_url"]
    return old


def build(specs, destination, *, live_url=None, archive_url=None, allow_incomplete=False, preserve=False):
    """Stage files before replacing the portal data."""
    destination = Path(destination).resolve()
    destination.mkdir(parents=True, exist_ok=True)
    generated = destination / "evidence"
    if generated.exists() and (generated.is_symlink() or not (generated / ".shoptrace-generated").is_file()):
        raise ValueError("Refusing to replace a non-generated evidence directory")
    for value in (live_url, archive_url):
        if value:
            parsed = urlsplit(value)
            if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
                raise ValueError("Published service and archive URLs must be HTTPS without credentials")
    old, offset = None, 0
    if preserve:
        if not generated.is_dir() or not (destination / "report.json").is_file():
            raise ValueError("Preserving results requires an existing portal report and evidence")
        old = read(destination / "report.json")
        if old.get("schema_version") != "shoptrace.portal.v1":
            raise ValueError("The existing portal schema is not supported")
        for path in generated.rglob("*"):
            if path.is_symlink():
                raise ValueError("Saved evidence must not contain symbolic links")
        indices = [int(path.name[6:]) for path in generated.iterdir()
                   if path.is_dir() and re.fullmatch(r"group-\d+", path.name)]
        offset = max(indices, default=-1) + 1
    with tempfile.TemporaryDirectory(prefix=".shoptrace-portal-", dir=destination.parent) as temporary:
        staged = Path(temporary)
        report = _build(specs, staged, live_url=live_url, archive_url=archive_url,
                        allow_incomplete=allow_incomplete, offset=offset)
        if old is not None:
            report = _merge(old, report)
            shutil.copytree(generated, staged / "evidence", dirs_exist_ok=True)
            raw = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
            (staged / "report.json").write_text(raw, encoding="utf-8")
            encoded = json.dumps(report, ensure_ascii=False).replace("<", "\\u003c").replace("\u2028", "\\u2028").replace("\u2029", "\\u2029")
            (staged / "report-data.js").write_text("window.SHOPTRACE_REPORT = " + encoded + ";\n", encoding="utf-8")
        if generated.exists():
            shutil.rmtree(generated)
        (staged / "evidence").replace(generated)
        for name in ("report.json", "report-data.js"):
            (staged / name).replace(destination / name)
    files = [{"path": p.relative_to(destination).as_posix(), "bytes": p.stat().st_size,
              "sha256": hashlib.sha256(p.read_bytes()).hexdigest()}
             for p in sorted(destination.rglob("*")) if p.is_file() and p.name != "manifest.json"]
    (destination / "manifest.json").write_text(json.dumps({"schema_version": "shoptrace.portal.manifest.v1", "files": files}, indent=2) + "\n")
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--suite", type=parse_suite, action="append", required=True, metavar="SUITE[:ARM]=DIRECTORY")
    parser.add_argument("--output", type=Path, default=ROOT / "dist")
    parser.add_argument("--live-url")
    parser.add_argument("--archive-url")
    parser.add_argument("--allow-incomplete", action="store_true", help="For local development only; labels remain actual statuses.")
    parser.add_argument("--preserve", action="store_true", help="Append new attempts while retaining all saved report evidence.")
    args = parser.parse_args()
    try:
        report = build(args.suite, args.output, live_url=args.live_url, archive_url=args.archive_url,
                       allow_incomplete=args.allow_incomplete, preserve=args.preserve)
    except (ValueError, OSError, KeyError, TypeError) as exc:
        parser.exit(1, f"Portal build stopped: {type(exc).__name__}: {exc}\n")
    print(json.dumps({"suites": len(report["suites"]), "attempts": sum(len(s["attempts"]) for s in report["suites"]), "output": str(args.output)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
